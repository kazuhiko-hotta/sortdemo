"""
挿入ソートアルゴリズムモジュール。

挿入ソートは、配列を「整列済み部分」と「未整列部分」に分け、
未整列部分の先頭要素を整列済み部分の適切な位置に挿入していく
アルゴリズム。トランプのカードを手に持って並べ替えるイメージ。

計算量:
  - 最悪・平均: O(n²)
  - 最良（整列済み）: O(n)
  - 空間: O(1)（インプレース）
"""


class InsertionSort:
    """挿入ソートの可視化用実装。

    ジェネレータベースで1ステップずつソートを進め、
    各ステップで操作中のインデックスとステップ数を返す。

    Attributes:
        data (list[int]): ソート対象のデータ配列（インプレースで変更される）
    """

    def __init__(self, data):
        """挿入ソートインスタンスを初期化する。

        Args:
            data (list[int]): ソート対象のデータ配列
        """
        self.data = data

    def sort(self):
        """挿入ソートをジェネレータとして実行する。

        data[0] は整列済みとして、data[1] から順に各要素を
        整列済み部分の正しい位置に挿入する。

        Yields:
            tuple[list[int], int]: (アクティブなインデックスのリスト, 累計ステップ数)
                - 挿入対象の選択時: [挿入する要素, 比較先]
                - シフト中: [シフト先, 挿入元の位置]
                - 挿入完了時: [挿入位置]
        """
        n = len(self.data)
        steps = 0

        for i in range(1, n):
            # 挿入する要素（キー）を一時保存
            key = self.data[i]
            # 整列済み部分の末尾から比較していく
            j = i - 1

            steps += 1
            # 挿入対象と比較先をハイライト
            yield [i, j], steps

            # キーより大きい要素を右にシフトして挿入位置を探す
            while j >= 0 and key < self.data[j]:
                steps += 1
                # 要素を1つ右にシフト
                self.data[j + 1] = self.data[j]
                j -= 1
                # シフト中の状態をハイライト
                yield [j + 1, i], steps

            # 見つかった位置にキーを挿入
            self.data[j + 1] = key
            # 挿入完了位置をハイライト
            yield [j + 1], steps
